def count_ingredients(description):
    """Count unique ingredient items in description."""
    if not description:
        return 0
    text = description.lower()
    found = set()
    multi_keywords = [
        "охотничьи колбаски", "болгарский перец", "помидоры черри",
        "сладкий чили", "чесночный соус", "сливочный соус",
        "томатный соус", "терияки соус", "барбекю соус",
        "ранч соус", "тар-тар соус", "бургер соус",
        "огурчики", "колбаски",
    ]
    for kw in multi_keywords:
        if kw in text:
            if "колбаски" in kw:
                found.add("колбаски")
            elif "перец" in kw:
                found.add("перец")
            elif "помидор" in kw:
                found.add("помидоры")
            elif "огурчик" in kw:
                found.add("огурчики")
    for ing in INGREDIENTS:
        if ing in text:
            found.add(ing)
    for s in SOUL:
        found.discard(s)
    return len(found)
